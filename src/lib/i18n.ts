const LANG_KEY = "bharatkhoj_lang";

export function getCurrentLanguage(): LanguageCode {
  if (typeof window === "undefined") return "en";
  const saved = localStorage.getItem(LANG_KEY) as LanguageCode | null;
  return saved && TRANSLATIONS[saved] ? saved : "en";
}

export function setLanguage(lang: LanguageCode): void {
  if (typeof window !== "undefined") {
    localStorage.setItem(LANG_KEY, lang);
    window.dispatchEvent(new Event("bharatkhoj_lang_change"));
  }
}

export function t(key: string, lang?: LanguageCode): string {
  const current = lang || getCurrentLanguage();
  return TRANSLATIONS[current]?.[key] || TRANSLATIONS.en[key] || key;
}
